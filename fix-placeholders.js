// Path to the placeholder image
const imagePath = path.join(__dirname, 'app', 'assets', 'images', 'placeholder.png');

try {
  // Create the directory structure if it doesn't exist
  const dir = path.dirname(imagePath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  // Write the PNG file
  fs.writeFileSync(imagePath, pngHeader);
  console.log(`Successfully created placeholder image at ${imagePath}`);
} catch (error) {
  console.error(`Error creating placeholder image: ${error.message}`);
} 